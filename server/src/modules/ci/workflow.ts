import { parse } from 'yaml';
import type { CiPostAs, CiTrigger, CiWorkflowViolation } from '@devdigest/shared';
import {
  CI_ACTION_CHECKOUT,
  CI_ACTION_UPLOAD_ARTIFACT,
  CI_ALLOWED_PERMISSIONS,
  CI_ARTIFACT_NAME,
  CI_FORBIDDEN_TRIGGERS,
  CI_JOB_ID,
  CI_RESULT_FILE,
  CI_RUNNER_PATH,
  CI_WORKFLOW_NAME,
  CI_WORKFLOW_VERSION,
} from './constants.js';

/**
 * Pure: the generated GitHub Actions workflow and the validator that guards
 * install / zip. No I/O.
 *
 * Security shape (do not loosen without a review):
 *  - `pull_request` only (never `pull_request_target`);
 *  - permissions exactly `contents: read` + `pull-requests: write`;
 *  - checks out the BASE sha with `persist-credentials: false`, so the PR's own
 *    code never runs with the OpenRouter key; a PR that edits the runner has no effect;
 *  - fork PRs skip the single `review` job (no secrets are available to them);
 *  - no PR-controlled text in any `run:` (values reach the shell via `env:` only).
 */

export interface RenderWorkflowInput {
  triggers: readonly CiTrigger[];
  postAs: CiPostAs;
}

const SAME_REPO = 'github.event.pull_request.head.repo.full_name == github.repository';

export function renderWorkflow({ triggers, postAs }: RenderWorkflowInput): string {
  return `# devdigest-workflow-version: ${CI_WORKFLOW_VERSION}
# Generated by DevDigest. Re-export the agent from DevDigest to update it.
name: ${CI_WORKFLOW_NAME}

on:
  pull_request:
    types: [${triggers.join(', ')}]

permissions:
  contents: read
  pull-requests: write

jobs:
  ${CI_JOB_ID}:
    name: ${CI_WORKFLOW_NAME}
    # Fork PRs get no secrets, so the job is skipped for them.
    if: ${SAME_REPO}
    runs-on: ubuntu-latest
    steps:
      - name: Check out the base revision
        uses: ${CI_ACTION_CHECKOUT.uses} # ${CI_ACTION_CHECKOUT.tag}
        with:
          ref: \${{ github.event.pull_request.base.sha }}
          persist-credentials: false

      - name: Run the DevDigest agent
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ github.token }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
          DEVDIGEST_POST_AS: ${postAs}
        run: |
          if [ ! -f ${CI_RUNNER_PATH} ]; then
            echo "DevDigest is not installed on the base branch yet. Merge the install PR, then re-run." >> "$GITHUB_STEP_SUMMARY"
            exit 0
          fi
          node ${CI_RUNNER_PATH}

      - name: Upload the result
        if: always()
        uses: ${CI_ACTION_UPLOAD_ARTIFACT.uses} # ${CI_ACTION_UPLOAD_ARTIFACT.tag}
        with:
          name: ${CI_ARTIFACT_NAME}
          path: ${CI_RESULT_FILE}
          if-no-files-found: ignore

`;
}

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Trigger names declared under `on:` (string, list or map form). */
function triggerNames(on: unknown): string[] {
  if (typeof on === 'string') return [on];
  if (Array.isArray(on)) return on.filter((x): x is string => typeof x === 'string');
  if (isObj(on)) return Object.keys(on);
  return [];
}

/** A `permissions:` value is acceptable only when it grants no more than the allowed scopes. */
function permissionsExceed(perms: unknown): boolean {
  if (perms === undefined) return false;
  if (!isObj(perms)) return true; // 'write-all' / 'read-all' / junk
  return Object.entries(perms).some(([scope, level]) => {
    const allowed = CI_ALLOWED_PERMISSIONS[scope];
    return !allowed || typeof level !== 'string' || !allowed.includes(level);
  });
}

const PINNED = /@[0-9a-f]{40}$/;

function isUnpinned(uses: unknown): boolean {
  if (typeof uses !== 'string') return false;
  if (uses.startsWith('./')) return false; // local action / workflow
  return !PINNED.test(uses);
}

/** Validate a workflow text against the four install-blocking rules. */
export function validateWorkflow(text: string): CiWorkflowViolation[] {
  let doc: unknown;
  try {
    doc = parse(text);
  } catch (err) {
    return [{ rule: 'yaml_invalid', message: `Workflow is not valid YAML: ${(err as Error).message}` }];
  }
  if (!isObj(doc)) {
    return [{ rule: 'yaml_invalid', message: 'Workflow must be a YAML mapping.' }];
  }

  const violations: CiWorkflowViolation[] = [];

  for (const name of triggerNames(doc.on)) {
    if ((CI_FORBIDDEN_TRIGGERS as readonly string[]).includes(name)) {
      violations.push({
        rule: 'forbidden_trigger',
        message: `Trigger "${name}" is not allowed: it exposes secrets to untrusted pull request code.`,
      });
    }
  }

  const jobs = isObj(doc.jobs) ? doc.jobs : {};
  if (permissionsExceed(doc.permissions)) {
    violations.push({
      rule: 'extra_permissions',
      message: 'Workflow permissions must be at most "contents: read" and "pull-requests: write".',
    });
  }
  // No `permissions:` anywhere means GitHub hands the token the repository default (read/write on older
  // repos and orgs). Require an explicit block at workflow level, or on every job.
  if (doc.permissions === undefined) {
    const undeclared = Object.entries(jobs)
      .filter(([, job]) => isObj(job) && job.permissions === undefined)
      .map(([jobId]) => jobId);
    if (undeclared.length > 0) {
      violations.push({
        rule: 'extra_permissions',
        message: `Declare "permissions" explicitly (contents: read, pull-requests: write) at workflow level or on job "${undeclared.join('", "')}"; otherwise GitHub gives the token the repository default.`,
      });
    }
  }
  for (const [jobId, job] of Object.entries(jobs)) {
    if (!isObj(job)) continue;
    if (permissionsExceed(job.permissions)) {
      violations.push({
        rule: 'extra_permissions',
        message: `Job "${jobId}" requests permissions beyond "contents: read" and "pull-requests: write".`,
      });
    }
    const steps = Array.isArray(job.steps) ? job.steps : [];
    const usesList = [job.uses, ...steps.map((s) => (isObj(s) ? s.uses : undefined))];
    for (const uses of usesList) {
      if (isUnpinned(uses)) {
        violations.push({
          rule: 'unpinned_action',
          message: `"${String(uses)}" must be pinned to a full 40-character commit SHA.`,
        });
      }
    }
  }
  return violations;
}
